/* Generates the two Twilight Marked panel motifs.
 *
 *     node tools/make-marked-motifs.mjs
 *
 * These are *masks*, not pictures: everything is white and the only thing
 * that varies is opacity, so `marked.css` decides the hue, the falloff and
 * the glow, and one drawing serves both the dark and the inverted stock. An
 * <img> would have baked all three.
 *
 * They are generated rather than hand-plotted because both figures are
 * arithmetic that a person is bad at. A honeycomb has to be a real lattice
 * or it reads as chicken wire drawn by hand, and a vine has to actually
 * taper — a taper is a polygon offset along a curve's normals, which is not
 * something you author as a `d` string. The first hand-drawn pair came out
 * as a barcode and a field of grass, which is what this file exists to stop
 * happening again.
 *
 * The randomness is seeded, so the committed SVGs are reproducible: run it
 * twice and git sees nothing. There is no Math.random here for that reason.
 *
 * viewBox is `0 60 300 120` on both — a 5:2 intrinsic ratio. The CSS scales
 * the motif off the panel's *width* and anchors it to the bottom, so that
 * ratio is what decides how far up the panel the drawing reaches, and it is
 * the same number for both decks so the two cards agree.
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../design/assets/marked');
const VB = { x: 0, y: 60, w: 300, h: 120 };
const FLOOR = 180;              // the panel's bottom edge, in viewBox units
const n = v => Math.round(v * 100) / 100;

/* mulberry32 — small, fast, and the same sequence on every machine. */
function rng(seed){
  return function(){
    seed |= 0; seed = seed + 0x6D2B79F5 | 0;
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

/* ══════════════════════════════════════════════════════════════════
   VOID — a hexagonal crystal lattice.

   A real honeycomb: pointy-top cells on the standard offset grid, so
   dx = √3·r and dy = 1.5·r with alternate rows shifted half a cell. Drawn
   whole and then *read* by the CSS falloff, which is why the lattice runs
   past every edge — a pattern that stops inside the card reads as a decal
   stuck on it rather than as something the card is made of.

   What stops it reading as chicken wire is that the lattice is not uniform.
   Three passes: every cell at a whisper, a seeded minority at full strength
   with a faint face, and a smaller minority carrying an inner ring and three
   facet spokes. That is a crystal *formation* — dense where it has grown,
   thin where it has not — rather than graph paper.

   The fills are deliberately the weakest thing here. A grimoire fills the
   panel to the footer and its last feature run lands on the drawing, and a
   broad fill behind body text costs far more contrast than a 1.5px stroke
   crossing it does.
   ══════════════════════════════════════════════════════════════════ */
function hexPath(cx, cy, r){
  const p = [];
  for(let i = 0; i < 6; i++){
    const a = (90 + i * 60) * Math.PI / 180;
    p.push(`${n(cx + r * Math.cos(a))} ${n(cy - r * Math.sin(a))}`);
  }
  return 'M' + p.join('L') + 'Z';
}

function void_(){
  const R = 15, dx = Math.sqrt(3) * R, dy = 1.5 * R;
  const rand = rng(0x5741);
  const cells = [];
  for(let row = 0, cy = FLOOR + R; cy > VB.y - R; row++, cy -= dy){
    const off = (row % 2) ? dx / 2 : 0;
    for(let cx = -dx + off; cx < VB.w + dx; cx += dx) cells.push({cx, cy, row});
  }

  // Weighted toward the bottom: `depth` is 0 at the floor and 1 at the top,
  // and a cell is promoted less often the higher it sits. The formation
  // grows up out of the card's own edge.
  const depth = c => (FLOOR - c.cy) / VB.h;
  const lit  = cells.filter(c => rand() < 0.42 * (1 - depth(c) * 0.72));
  const core = lit.filter(() => rand() < 0.44);

  const base = cells.map(c => hexPath(c.cx, c.cy, R)).join('');
  const strong = lit.map(c => hexPath(c.cx, c.cy, R)).join('');
  const inner = core.map(c => hexPath(c.cx, c.cy, R * 0.54)).join('');
  const spokes = core.map(c => {
    let d = '';
    for(let i = 0; i < 6; i += 2){
      const a = (90 + i * 60) * Math.PI / 180;
      d += `M${n(c.cx)} ${n(c.cy)}L${n(c.cx + R * 0.54 * Math.cos(a))} ${n(c.cy - R * 0.54 * Math.sin(a))}`;
    }
    return d;
  }).join('');
  // The family rhombus, at the centre of a few of the lit cells.
  const pips = lit.filter(() => rand() < 0.16).map(c => {
    const s = 3.4;
    return `M${n(c.cx)} ${n(c.cy - s)}L${n(c.cx + s)} ${n(c.cy)}L${n(c.cx)} ${n(c.cy + s)}L${n(c.cx - s)} ${n(c.cy)}Z`;
  }).join('');

  return `<!-- GENERATED by tools/make-marked-motifs.mjs — do not edit by hand.
     Starbound · a hexagonal crystal lattice. A mask: white only, opacity is
     the drawing, and marked.css supplies hue, falloff and glow. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VB.x} ${VB.y} ${VB.w} ${VB.h}">
  <g fill="none" stroke="#fff" stroke-linejoin="round">
    <path d="${base}" stroke-width=".85" opacity=".15"/>
    <path d="${strong}" stroke-width="1.6" opacity=".5"/>
    <path d="${inner}" stroke-width="1" opacity=".3"/>
    <path d="${spokes}" stroke-width=".8" opacity=".22"/>
  </g>
  <path d="${lit.map(c => hexPath(c.cx, c.cy, R)).join('')}" fill="#fff" opacity=".07"/>
  <path d="${pips}" fill="#fff" opacity=".4"/>
</svg>
`;
}

/* ══════════════════════════════════════════════════════════════════
   ROOT — organic vines.

   A vine is told from a blade of grass by three things and none of them is
   the outline: it TAPERS, it FORKS, and it CURLS. So a strand here is a
   centreline walked with a slowly turning heading, drawn as a filled ribbon
   built by offsetting that centreline along its own normals — which is what
   makes the width fall continuously instead of in the steps a stack of
   strokes gives you. Branches fork off real points on the parent, tendrils
   spiral off the tips, and leaves hang off alternating sides.

   The heading turns on a sine plus a seeded wobble rather than on noise
   alone. Pure noise gives a drunk line; a sine alone gives a decorative
   scroll. The sum reads as something that grew.
   ══════════════════════════════════════════════════════════════════ */
function walk(x, y, heading, steps, step, curl, rand){
  const pts = [[x, y]];
  let a = heading;
  for(let i = 1; i <= steps; i++){
    a += Math.sin(i * curl.freq + curl.phase) * curl.amp + (rand() - 0.5) * curl.jit;
    x += Math.cos(a) * step; y += Math.sin(a) * step;
    pts.push([x, y]);
  }
  return pts;
}

/* Offset the centreline both ways along its normals and close the loop —
   one polygon, so the taper is continuous rather than stepped. */
function ribbon(pts, w0, w1){
  const L = [], Rr = [];
  for(let i = 0; i < pts.length; i++){
    const p = pts[i], q = pts[Math.min(i + 1, pts.length - 1)], o = pts[Math.max(i - 1, 0)];
    const dx = q[0] - o[0], dy = q[1] - o[1], m = Math.hypot(dx, dy) || 1;
    const w = (w0 + (w1 - w0) * (i / (pts.length - 1))) / 2;
    L.push([p[0] - dy / m * w, p[1] + dx / m * w]);
    Rr.push([p[0] + dy / m * w, p[1] - dx / m * w]);
  }
  const f = a => a.map(p => `${n(p[0])} ${n(p[1])}`).join('L');
  return `M${f(L)}L${f(Rr.reverse())}Z`;
}

function tendril(x, y, a0, turns, r0, rand){
  const pts = [];
  const N = 26;
  const dir = rand() < 0.5 ? 1 : -1;
  for(let i = 0; i <= N; i++){
    const t = i / N, a = a0 + dir * turns * Math.PI * 2 * t, r = r0 * (1 - t * 0.82);
    pts.push([x + Math.cos(a) * r - Math.cos(a0) * r0, y + Math.sin(a) * r - Math.sin(a0) * r0]);
  }
  return 'M' + pts.map(p => `${n(p[0])} ${n(p[1])}`).join('L');
}

/* A pointed oval: two quadratics meeting at the tip and the stem. */
function leaf(x, y, a, len, wid){
  const tx = x + Math.cos(a) * len, ty = y + Math.sin(a) * len;
  const nx = -Math.sin(a) * wid, ny = Math.cos(a) * wid;
  const mx = x + Math.cos(a) * len * 0.45, my = y + Math.sin(a) * len * 0.45;
  return `M${n(x)} ${n(y)}Q${n(mx + nx)} ${n(my + ny)} ${n(tx)} ${n(ty)}` +
         `Q${n(mx - nx)} ${n(my - ny)} ${n(x)} ${n(y)}Z`;
}

function root(){
  const rand = rng(0x2B17);
  const stems = [], branches = [], curls = [], leaves = [], buds = [];
  const BASES = [22, 74, 128, 182, 236, 288];

  for(const bx of BASES){
    const steps = 15 + Math.floor(rand() * 4);
    const pts = walk(bx + (rand() - 0.5) * 8, FLOOR + 4, -Math.PI / 2 + (rand() - 0.5) * 0.5,
      steps, 7.4, {freq: .52, phase: rand() * 6.28, amp: .17, jit: .2}, rand);
    stems.push(ribbon(pts, 7.2 + rand() * 1.6, 1.3));

    // Two forks, off real points on the parent rather than off the base.
    for(const t of [0.34, 0.63]){
      const i = Math.round(t * (pts.length - 1)), p = pts[i], q = pts[i + 1] || p;
      const a = Math.atan2(q[1] - p[1], q[0] - p[0]) + (rand() < 0.5 ? 1 : -1) * (0.7 + rand() * 0.5);
      const bp = walk(p[0], p[1], a, 8 + Math.floor(rand() * 3), 6.2,
        {freq: .6, phase: rand() * 6.28, amp: .2, jit: .26}, rand);
      branches.push(ribbon(bp, 3.4, 0.9));
      const tip = bp[bp.length - 1], pv = bp[bp.length - 2];
      if(rand() < 0.55)
        curls.push(tendril(tip[0], tip[1], Math.atan2(tip[1] - pv[1], tip[0] - pv[0]), 1.15, 6.5, rand));
      else
        buds.push(leaf(tip[0], tip[1], Math.atan2(tip[1] - pv[1], tip[0] - pv[0]), 9, 3.4));
    }

    // Leaves alternate sides down the stem.
    let side = rand() < 0.5 ? 1 : -1;
    for(const t of [0.3, 0.5, 0.68, 0.84]){
      const i = Math.round(t * (pts.length - 1)), p = pts[i], q = pts[i + 1] || p;
      const a = Math.atan2(q[1] - p[1], q[0] - p[0]) + side * (1.05 + rand() * 0.35);
      leaves.push(leaf(p[0], p[1], a, 10 + rand() * 5, 3.8 + rand() * 1.4));
      side = -side;
    }

    const tip = pts[pts.length - 1], pv = pts[pts.length - 2];
    curls.push(tendril(tip[0], tip[1], Math.atan2(tip[1] - pv[1], tip[0] - pv[0]), 1.35, 8, rand));
  }

  // Fine growth between the systems, so the floor is not a row of six stems.
  const fine = [];
  for(let i = 0; i < 11; i++){
    const p = walk(8 + i * 28 + (rand() - 0.5) * 14, FLOOR + 4, -Math.PI / 2 + (rand() - 0.5) * 0.8,
      5 + Math.floor(rand() * 4), 6, {freq: .7, phase: rand() * 6.28, amp: .24, jit: .32}, rand);
    fine.push(ribbon(p, 2.8, 0.8));
  }

  return `<!-- GENERATED by tools/make-marked-motifs.mjs — do not edit by hand.
     Rootwoken · organic vines. A mask: white only, opacity is the drawing,
     and marked.css supplies hue, falloff and glow. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VB.x} ${VB.y} ${VB.w} ${VB.h}" fill="#fff">
  <path d="${stems.join('')}" opacity=".54"/>
  <path d="${branches.join('')}" opacity=".4"/>
  <path d="${fine.join('')}" opacity=".26"/>
  <g fill="none" stroke="#fff" stroke-width="1.6" stroke-linecap="round" opacity=".36">
    <path d="${curls.join('')}"/>
  </g>
  <path d="${leaves.join('')}" opacity=".32"/>
  <path d="${buds.join('')}" opacity=".38"/>
</svg>
`;
}

mkdirSync(OUT, {recursive: true});
writeFileSync(resolve(OUT, 'void.svg'), void_());
writeFileSync(resolve(OUT, 'root.svg'), root());
console.log('wrote design/assets/marked/void.svg and root.svg');
